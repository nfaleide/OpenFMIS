"""Modus XML — import (ModusResult) and export (ModusSubmit) for soil tests.

The AgGateway Modus standard defines two primary document types:
- ModusResult: Lab results (parsed by ``parse_modus_xml``)
- ModusSubmit: Work orders (generated by ``generate_modus_submit``)
"""

