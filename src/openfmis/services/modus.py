# Reverse map: canonical parameter → Modus analyte name
_REVERSE_ANALYTE: dict[str, str] = {
    "pH": "pH",
    "P": "Phosphorus",
    "K": "Potassium",
    "OM": "Organic Matter",
    "CEC": "CEC",
    "S": "Sulfur",
    "Zn": "Zinc",
    "Mn": "Manganese",
    "Fe": "Iron",
    "Cu": "Copper",
    "B": "Boron",
    "Ca": "Calcium",
    "Mg": "Magnesium",
    "Na": "Sodium",
    "NO3": "Nitrate",
    "SO4": "Sulfate",
    "Buffer pH": "Buffer pH",
}


def generate_modus_submit(
    *,
    submitter_name: str,
    lab_name: str,
    field_name: str,
    sample_points: list[dict[str, Any]],
    requested_analyses: list[str] | None = None,
    sample_depth: float | None = None,
    depth_unit: str = "inches",
    notes: str | None = None,
) -> str:
    """Generate a Modus ModusSubmit XML work order.

    Args:
        submitter_name: Name of the person/org submitting the work order.
        lab_name: Target lab name.
        field_name: Field name for reference.
        sample_points: List of dicts with ``sample_id`` (str), and optionally
            ``latitude`` (float), ``longitude`` (float).
        requested_analyses: List of canonical analyte names (e.g. ["pH", "P", "K"]).
            If None, a standard soil test panel is used.
        sample_depth: Sample depth value.
        depth_unit: Depth unit (default "inches").
        notes: Optional notes to include.

    Returns:
        UTF-8 encoded XML string.
    """
    ns = "http://www.aggateway.org/Modus"

    root = ET.Element("ModusSubmit", xmlns=ns)

    ET.SubElement(root, "SubmitterName").text = submitter_name
    ET.SubElement(root, "LabName").text = lab_name
    ET.SubElement(root, "FieldName").text = field_name
    ET.SubElement(root, "SubmitDate").text = datetime.now().strftime("%Y-%m-%dT%H:%M:%S")

    if notes:
        ET.SubElement(root, "Notes").text = notes

    # Default standard soil panel
    if requested_analyses is None:
        requested_analyses = [
            "pH",
            "P",
            "K",
            "OM",
            "CEC",
            "S",
            "Zn",
            "Mn",
            "Fe",
            "Cu",
            "B",
            "Ca",
            "Mg",
            "Na",
            "Buffer pH",
        ]

    # Requested analyses
    analyses_elem = ET.SubElement(root, "RequestedAnalyses")
    for param in requested_analyses:
        modus_name = _REVERSE_ANALYTE.get(param, param)
        ae = ET.SubElement(analyses_elem, "Analysis")
        ET.SubElement(ae, "AnalyteName").text = modus_name

    # Samples
    samples_elem = ET.SubElement(root, "Samples")
    for sp in sample_points:
        sample = ET.SubElement(samples_elem, "Sample")
        ET.SubElement(sample, "SampleID").text = str(sp.get("sample_id", ""))

        if sample_depth is not None:
            ET.SubElement(sample, "Depth").text = str(sample_depth)
            ET.SubElement(sample, "DepthUnit").text = depth_unit

        lat = sp.get("latitude")
        lon = sp.get("longitude")
        if lat is not None and lon is not None:
            ET.SubElement(sample, "Latitude").text = str(lat)
            ET.SubElement(sample, "Longitude").text = str(lon)

    ET.indent(root, space="  ")
    return ET.tostring(root, encoding="unicode", xml_declaration=True)
